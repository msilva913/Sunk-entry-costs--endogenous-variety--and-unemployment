function [lhs, rhs] = static_resid(y, x, params)
T = NaN(5, 1);
lhs = NaN(14, 1);
rhs = NaN(14, 1);
T(1) = y(2)^(-params(4));
T(2) = params(6)*exp(y(5))*(y(3)/y(4))^(params(6)-1);
T(3) = T(2)+1-params(5);
T(4) = exp(y(5))*y(3)^params(6);
T(5) = y(4)^(1-params(6));
lhs(1) = T(1);
rhs(1) = T(1)*params(1)*T(3);
lhs(2) = params(2)*y(4)^(1/params(3));
rhs(2) = T(1)*y(7);
lhs(3) = y(3);
rhs(3) = y(3)*(1-params(5))+y(8);
lhs(4) = y(1);
rhs(4) = y(2)+y(8);
lhs(5) = y(1);
rhs(5) = T(4)*T(5);
lhs(6) = y(7);
rhs(6) = y(1)*(1-params(6))/y(4);
lhs(7) = y(6);
rhs(7) = y(1)*params(6)*4/y(3);
lhs(8) = y(5);
rhs(8) = y(5)*params(7)+x(1);
lhs(9) = y(9);
rhs(9) = 100*log(y(1));
lhs(10) = y(10);
rhs(10) = 100*log(y(3));
lhs(11) = y(11);
rhs(11) = 100*log(y(2));
lhs(12) = y(12);
rhs(12) = 100*log(y(4));
lhs(13) = y(13);
rhs(13) = 100*log(y(7));
lhs(14) = y(14);
rhs(14) = 100*log(y(8));
end
