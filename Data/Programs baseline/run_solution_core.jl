# =============================================================================
# Model equations (41 = 8 states + 33 controls)
# =============================================================================
#   f[1]–f[2]    exit: cutoff, realized measured exit rate
#   f[3]–f[5]    forward-looking: job creation, business formation, flow value of a vacancy
#   f[6]–f[8]    recruiter compensation, Nash wage, vacancy entry
#   f[9]–f[15]   matching, employment, goods market
#   f[16]–f[21]  resource constraint, entry, free entry, GDP, profits, vacancy pool
#   f[22]–f[24]  post-exit stocks (same-period controls)
#   f[25]–f[28]  laws of motion of the pre-exit states
#   f[29]        bookkeeping lag δl_{t+1} = δ_t
#   f[30]–f[35]  labor share and observables
#   f[36]–f[38]  shock processes
#   f[39]–f[41]  reposting: Λ_r, Q^rep, H
# Unprimed = t, primed = t+1. Indices f[1]–f[24] are stable; runners override f[13]
# (no-variety comparison) and sigma_determinacy.jl overrides f[4], f[22].
function gen_model_equations()
    f = fill(Sym("x"), nvar)

    # Survival probabilities and the t→t+1 survival factor
    Λ        = (1 - p_0) + p_0 * (x_c  / f_m)^ψ     # Λ_t = F(x_c,t)
    Λp       = (1 - p_0) + p_0 * (x_cp / f_m)^ψ     # Λ_{t+1}
    SDF_surv = (1 - δ * δbar) * Λp                   # (1 − δ_t)Λ_{t+1}
    m        = β * λp / λ                            # m_{t+1}

    # Reposting shortfall 𝓡_t = E_t[m(1−δ_t)Λ_{t+1}(Q_{t+1} − Q^rep_{t+1})] (eq:repost_shortfall).
    # Written as (Q − K) − H using f[5]; it is exactly 0 under costless reposting, so it is not
    # a logged variable itself.
    R_sh  = Q  - K  - H
    R_shp = Qp - Kp - Hp

    # ── Exit ─────────────────────────────────────────────────────────────────
    # [1] A line continues iff its draw is below gross profit per line plus its value
    #     (eq:cutoff_eq)
    f[1] = x_c - (Y_c * (μ - 1) / (μ * N) + ν_f)
    # [2] Realized measured exit rate (eq:delta_e_lom): destruction at the end of t−1 plus the
    #     period-t exit draw, δ_e,t = 1 − (1−δ_{t−1})Λ_t. Uses the bookkeeping state δl.
    f[2] = δ_e - (1 - (1 - δl * δbar) * Λ)

    # ── Forward-looking equations ────────────────────────────────────────────
    # [3] Job creation (eq:jcc_eq): average hiring cost = discounted, survival-weighted
    #     recruiter surplus, wage substituted. The shortfall enters with (1−ϕ): the
    #     recruiter's share.
    f[3] = κ + K/q - m * SDF_surv * (
               (1 - ϕ) * (w_intp - Kp - b)
               - ϕ * θp * (Kp + qp * κ)
               + (1 - sp * sbar) * (κ + Kp / qp)
               - (1 - ϕ) * sp * sbar * R_shp)
    # [4] Business formation (eq:N_euler_eq): value of a line = discounted value plus dividend
    f[4] = ν_f - m * SDF_surv * (ν_fp + d_fp)
    # [5] Flow value of a vacancy (eq:K): what holding it for one period is worth
    f[5] = K - (Q - m * SDF_surv * Qp)

    # ── Recruiter compensation, wage, vacancy entry ──────────────────────────
    # [6] w^int = ρ(N) z/μ (eq:recruiter_compensation): variety raises what a worker is worth
    f[6] = w_int - ρ * z * zbar / μ
    # [7] Nash wage (eq:wage_eq); the worker bears share ϕ of the shortfall s𝓡
    f[7] = w - (ϕ * (w_int - K + θ * (K + q * κ) - s * sbar * R_sh) + (1 - ϕ) * b)
    # [8] Vacancy entry e = G(Q) inverted (eq:entry_eq): Q = x_m e^{ξ_inv}
    f[8] = Q - x_m * e^ξ_inv

    # ── Matching, employment, goods market ───────────────────────────────────
    f[9]  = θ - v / u                       # [9]  tightness
    f[10] = q - A * θ^(-η_L)                # [10] vacancy-filling rate
    f[11] = L - (1 - u)                     # [11] employment
    f[12] = L - (L_c + L_e)                 # [12] retail plus entry labor
    f[13] = ρ - N^(1 / (ε - 1))             # [13] relative price (DS-CES)
    f[14] = λ - C^(-σ)                      # [14] marginal utility
    f[15] = Y_c - ρ * z * zbar * L_c        # [15] retail output

    # ── Resource constraint and identities ───────────────────────────────────
    # [16] Y^c = C + X + X^c + X^r (eq:rc). Survivors pay the conditional mean continuation
    #      cost (eq:agg_fixed_costs). Reactivation costs are paid on the Λ_t·Ṽ^s_t positions
    #      vacated at surviving lines; the cost per vacated position Q·Λ_r − Q^rep already
    #      embeds Λ_r (eq:agg_repost_costs).
    X   = e / (1 + ξ_inv) * Q + κ * q * v                 # sunk creation + hiring costs
    X_c = N * ψ_c * x_c * p_0 * (x_c / f_m)^ψ / Λ          # continuation costs
    X_r = Λ * Vs * (Q * Λ_r - Q_rep)                       # reactivation costs
    f[16] = Y_c - (C + X + X_c + X_r)
    f[17] = N_e - z * zbar * L_e / f_e      # [17] new lines use labor
    f[18] = ν_f - ρ * f_e / μ               # [18] free entry of product lines (eq:free_entry)
    f[19] = Y - (C + ν_f * N_e)             # [19] GDP (eq:gdp)
    f[20] = N * d_f - (Y_c * (μ - 1) / μ - X_c)   # [20] retail profits net of continuation costs
    f[21] = v - (v_pret + e)                # [21] vacancy pool = inherited + entrants

    # ── Post-exit stocks (solved jointly with the cutoff) ────────────────────
    # The exit draw against x_c,t turns pre-exit stocks into the stocks that produce and match
    # in t; x_c,t depends on N_t through f[1], so N_t is not predetermined.
    f[22] = N - Λ * Nt                      # [22] lines (eq:firm_law_motion)
    f[23] = u - (1 - Λ * Et)                # [23] unemployment before matching (eq:u_lom)
    f[24] = v_pret - Λ * (Vu + Λ_r * Vs)    # [24] inherited vacancies; 1 − Λ_r of the vacated
                                            #      positions are retired (eq:v_lom)

    # ── Laws of motion of the pre-exit states (Convention A) ─────────────────
    # δ_t destroys at the end of t; s_t separates only matches that produced in t, so a new
    # match faces δ_t and the t+1 exit draw but not s_t.
    f_t = A * θ^(1 - η_L)                   # job-finding rate
    S_t = 1 - δ * δbar                      # survival of exogenous destruction
    f[25] = Ntp - S_t * (N + N_e)                                   # [25]
    f[26] = Etp - S_t * ((1 - s * sbar) * (1 - u) + f_t * u)        # [26]
    f[27] = Vup - S_t * (1 - q) * v                                 # [27]
    f[28] = Vsp - S_t * s * sbar * (1 - u)                          # [28]
    # [29] Bookkeeping lag δl_{t+1} = δ_t, used only in f[2] (see the state declaration)
    f[29] = log(δlp) - log(δ)

    # ── Labor share and observables ──────────────────────────────────────────
    f[30] = ls - w * L / Y                  # [30] labor share
    f[31] = labor_prod - Y / (ρ * L)        # [31] measured labor productivity
    f[32] = C_R  - C / ρ                    # [32]–[35] price-deflated aggregates
    f[33] = Y_R  - Y / ρ
    f[34] = Y_cR - Y_c / ρ
    f[35] = w_R  - w / ρ

    # ── Shock processes (eq:ar1_z – eq:ar1_s) ────────────────────────────────
    f[36] = log(zp) - ρ_z * log(z)
    f[37] = log(δp) - ρ_δ * log(δ)
    f[38] = log(sp) - ρ_s * log(s)

    # ── Partial reposting (eq:Lambda_r, eq:Qrep) ─────────────────────────────
    # A vacated position is resumed iff αχ ≤ Q_t, with χ ~ F (the continuation-cost distribution).
    # rp switches the margin on (1) or to costless reposting (0).
    f[39] = Λ_r - (1 - rp + rp * ((1 - p_0) + p_0 * (Q / (α * f_m))^ψ))   # [39] Λ_r = F(Q/α)
    f[40] = Q_rep - Q * (Λ_r - rp * ψ_c * (Λ_r - 1 + p_0))               # [40] E max(Q − αχ, 0)
    f[41] = H - m * SDF_surv * Q_repp                                   # [41] H = E[m(1−δ)Λ'Q^rep']

    return f
end

