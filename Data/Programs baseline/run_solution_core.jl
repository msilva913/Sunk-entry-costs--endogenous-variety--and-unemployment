"""
    repost_par(cal) → (α, rp)

The last two entries of PAR. `rp` is the **reposting switch**: rp = 1 is partial reposting,
Λ_r = F(Q/α); rp = 0 is costless reposting (Block 1: Λ_r ≡ 1, Q^rep = Q, X^r = 0, 𝓡 = 0).
The switch exists because the costless case cannot be reached through α itself: α = 0
divides by zero in Q/(α χ_m), and Λ̄_r = 1 sits on F's kink. calibrate_shares returns
α = 0 without a reposting target; then rp = 0 and α = 1.0 is an inert placeholder.
"""
repost_par(cal) = (hasproperty(cal, :α) && cal.α > 0) ? (cal.α, 1.0) : (1.0, 0.0)

"""
    SHOCKS_BASE

Monthly shock processes for the runners. z and δ: bivariate SVAR (part6b), quarterly
persistence converted via ρ_q^(1/3). s: AR(1) on s = (τ−δ_e)/(1−δ_e), part6b. Placeholder
until the trivariate (z, δ, s) VAR of Q2 replaces all three. Pass a modified copy, e.g.
`merge(SHOCKS_BASE, (ρδ = 0.9,))`; never assign numbers to the symbolic ρ_z, σ_z, ….
"""
const SHOCKS_BASE = (ρz = 0.902, σz = 0.0092, ρδ = 0.592, σδ = 0.0669, ρs = 0.8741, σs = 0.0854)

"""
    build_PAR(cal, shocks) → Vector{Float64}

PAR in the order of `parameters`, from a calibration and shock processes
(ρz, σz, ρδ, σδ, ρs, σs). Runners should build PAR this way rather than by hand.
"""
function build_PAR(cal, shk)
    α_r, rp_r = repost_par(cal)
    return [cal.f_e; cal.z; cal.δ; cal.s; cal.b; cal.ϕ; cal.r; cal.σ; cal.ε; cal.A; cal.η_L;
            cal.κ; cal.ξ_inv; cal.x_m; cal.ψ; cal.f_m; cal.p_0;
            shk.ρz; shk.σz; shk.ρδ; shk.σδ; shk.ρs; shk.σs; α_r; rp_r]
end

"""
    shock_col(state, sd) → nx × 1 matrix

Single-shock impact column for `simulate_model`, built by state name (:z, :δ, :s) so it
survives changes to the state vector. `simulate_model` enters the shock at row 2.
"""
function shock_col(state::Symbol, sd)
    col = zeros(nx, 1)
    i = findfirst(==(state), Symbol.(x))
    isnothing(i) && error("shock_col: no state named $state in $(Symbol.(x))")
    col[i, 1] = sd
    return col
end

"""
    solution_interface(model, PAR, SS; ss_tol = 1e-8)

Evaluates the Jacobian at the numeric steady state SS (from SS_numeric) and solves the
first-order system. Two guards, both deliberate:
- the SS residual must be below ss_tol. A first-order solution around a non-steady point
  still returns well-formed, plausible-looking IRFs, so this failure is otherwise silent;
- the Blanchard–Kahn count must be exact. first_order flags a failure but still returns
  gx/hx sized by the number of stable roots. Small σ fails this way (sigma_determinacy.jl).
"""
function solution_interface(model, PAR, SS::Union{Vector{Float64},Nothing} = nothing;
                            ss_tol::Float64 = 1e-8)
    isnothing(SS) && error("solution_interface: pass the numeric steady state, " *
                           "SS_numeric(PAR, targets). The symbolic SS path is retired.")
    # eval_* are generated by process_model; invokelatest avoids Julia 1.12 world-age issues
    eta    = Base.invokelatest(getfield(Main, :eval_ShockVAR), PAR)
    PAR_SS = Base.invokelatest(getfield(Main, :eval_PAR_SS),  PAR)
    SS_err = Base.invokelatest(getfield(Main, :eval_SS_error), PAR_SS, SS)
    deriv  = Base.invokelatest(getfield(Main, :eval_deriv),    PAR_SS, SS)

    SS_max = maximum(abs.(SS_err))
    println("Max SS residual: $SS_max")
    SS_max > ss_tol && error("Steady-state residual $SS_max exceeds $ss_tol; worst equation " *
                             "is f[$(argmax(abs.(SS_err)))]. Fix the SS before trusting any IRF.")

    sol_mat = solve_model(model, deriv, eta)
    if sol_mat.qzflag != 1      # 1 unique, 0 none, 2 indeterminate, 3 invertibility violated
        what = Dict(0 => "no bounded equilibrium (too few stable roots)",
                    2 => "indeterminate (too many stable roots)",
                    3 => "invertibility condition fails (the stable block does not span the states)")
        error("Blanchard–Kahn failed: $(get(what, sol_mat.qzflag, "qzflag = $(sol_mat.qzflag)")). " *
              "Known thresholds: ε* = 2.40 (bk_epsilon_threshold.txt), σ* = 0.011 (sigma_determinacy.txt).")
    end
    println("Model solved")

    ss = NamedTuple(zip(model.varnames, exp.(SS[1:model.nvar])))   # levels
    return (SS = SS, ss = ss, eta = eta, deriv = deriv, sol_mat = sol_mat)
end

