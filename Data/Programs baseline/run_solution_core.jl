# run_solution_core.jl
# =============================================================================
# First-order perturbation of the baseline model (Draft.tex §2–3; spec:
# context/model_equations.md). Toolkit by Salazar-Perez and Seoane.
#
# Model: BGM business formation + a DMP labor market with sunk, finitely elastic
# vacancy creation (Gabrovski–Silva), endogenous exit through heterogeneous
# continuation costs, and partial reposting of vacated positions.
# Shocks: technology z, product destruction δ, match separation s (orthogonal; part6b).
#
# Timing within period t (draft fig:Timing; the draft is the reference model, S10):
#   1. z_t, δ_t, s_t are realized and known.
#   2. Exit draw against the cutoff x_c,t (survival Λ_t = F(x_c,t)); reactivation of positions
#      vacated at the end of t−1 (rate Λ_r,t); vacancy entry e_t = G(Q_t); new lines N^e_t.
#   3. Bargaining and production with N_t lines and 1 − u_t workers.
#   4. Matching out of v_t = v_pre,t + e_t and u_t.
#   5. Separation s_t and destruction δ_t take effect (incidence revealed).
# Survival from t to t+1 is (1 − δ_t)·Λ_{t+1}, the same object in every value equation and
# every law of motion.
#
# States are the PRE-EXIT stocks after the end-of-(t−1) incidence, plus the shocks. The
# post-exit stocks N_t, u_t, v_pre,t depend on x_c,t, so they are same-period controls.
#
# Usage: PAR = build_PAR(cal, shocks); SS = SS_numeric(PAR, targets);
#        sol = solution_interface(model, PAR, SS); IRF columns from shock_col(:δ, σ_δ).
# =============================================================================

