"""
    SS_numeric(PAR, targets) → Vector{Float64}

Log steady state in the order of `varnames` (current and next period), mapped from
steady_state(calibrate_shares(targets)), the construction steady_state_checks.jl certifies.
Do not reintroduce a parallel steady-state derivation here: an independent derivation
inconsistent with PAR is how the Sept 2026 free-entry residual bug arose. PAR must be the
vector build_PAR produces for the same targets.
"""
function SS_numeric(PAR::Vector{Float64}, targets)
    cal = calibrate_shares(targets)
    PAR_exp = build_PAR(cal, (ρz = PAR[18], σz = PAR[19], ρδ = PAR[20], σδ = PAR[21],
                              ρs = PAR[22], σs = PAR[23]))
    (length(PAR) == length(PAR_exp) &&
     all(isapprox.(PAR, PAR_exp; rtol = 1e-10, atol = 1e-14))) ||
        error("SS_numeric: PAR does not match build_PAR(calibrate_shares(targets), …). " *
              "PAR and the steady state would describe different economies.")

    st = steady_state(cal)
    @unpack u, N, v_pret, θ, q, L, v, e, K, Q, ρ, N_e, ν_f, d_f, w_int, w,
            L_e, L_c, Y_c, C, Y, x_c, δ_e, labor_share, Λ_r, R_sh = st

    # Pre-exit states: in steady state Λ = (1−δ_e)/(1−δ)
    Λ_s  = (1 - δ_e) / (1 - cal.δ)
    Nt_s = N / Λ_s
    Et_s = (1 - u) / Λ_s
    Vu_s = (1 - cal.δ) * (1 - q) * v
    # Floor: with s̄ = 0 (all separations destroy positions, Comparison A's CK arm) Ṽ^s ≡ 0,
    # but every variable is logged. The floor leaves f[28]'s residual at 1e-14.
    Vs_s = max((1 - cal.δ) * cal.s * (1 - u), 1e-14)
    isapprox(Λ_s * (Vu_s + Λ_r * Vs_s), v_pret; rtol = 1e-10) ||
        error("SS_numeric: pre-exit vacancy states inconsistent with v_pret")

    # Reposting: 𝓡 = (1−δ_e)(Q − Q^rep)/(1+r) and H = (1−δ_e)Q^rep/(1+r) = Q − K − 𝓡
    Q_rep_s = Q - (1 + cal.r) * R_sh / (1 - δ_e)
    H_s     = (1 - δ_e) * Q_rep_s / (1 + cal.r)

    SS_block = log.([
        Nt_s, Et_s, Vu_s, Vs_s, 1.0, 1.0, 1.0, 1.0,               # Nt Et Vu Vs z δ δl s
        θ, q, L, v, e, K, Q, ρ, N_e, ν_f, d_f, w_int, w, L_e, L_c, Y_c,
        C, C^(-cal.σ), Y, x_c, δ_e,
        Y / (ρ * L), C / ρ, Y / ρ, Y_c / ρ, w / ρ, labor_share,   # observables
        u, N, v_pret, Λ_r, Q_rep_s, H_s])
    length(SS_block) == nvar || error("SS_numeric: $(length(SS_block)) entries, need $nvar")
    return vcat(SS_block, SS_block)
end

